def bfs_reachable(adj: list[list[int]], start: int, blocked: set[int] = frozenset()) -> set[int]:
    """Return all the vertices that are reachable from the start vertex"""
    if start in blocked:
        return set()
    visited = {start}
    queue = deque([start])
    while queue:
        u = queue.popleft()
        for v in adj[u]:
            if v not in visited and v not in blocked:
                visited.add(v)
                queue.append(v)
    return visited


